create table if not exists public.food_menu (
  id bigint generated by default as identity primary key,
  category text not null default 'Signature Plates',
  title text not null,
  description text not null,
  price text not null,
  allergens text[] not null default '{}',
  featured boolean not null default false,
  image_url text,
  created_at timestamptz not null default now()
);

alter table public.food_menu enable row level security;

create policy "Public reads menu" on public.food_menu
for select using (true);

create policy "Staff manage menu" on public.food_menu
for all to authenticated
using (public.current_staff_role() in ('admin', 'receptionist'))
with check (public.current_staff_role() in ('admin', 'receptionist'));

