-- Migration to create public.gallery_images table for ODA Hotel Resort gallery
create table if not exists public.gallery_images (
  id bigint generated by default as identity primary key,
  src text not null,
  alt text not null default '',
  tag text not null default 'Resort',
  created_at timestamptz not null default now()
);

-- Enable Row Level Security
alter table public.gallery_images enable row level security;

-- Policies for public and authenticated access
create policy "Anyone can view gallery images"
  on public.gallery_images for select
  using (true);

create policy "Authenticated users can insert gallery images"
  on public.gallery_images for insert
  to authenticated
  with check (true);

create policy "Authenticated users can update gallery images"
  on public.gallery_images for update
  to authenticated
  using (true)
  with check (true);

create policy "Authenticated users can delete gallery images"
  on public.gallery_images for delete
  to authenticated
  using (true);

-- Allow anon client write access for dev / hotel admin console
create policy "Anon client can insert gallery images"
  on public.gallery_images for insert
  to anon
  with check (true);

create policy "Anon client can delete gallery images"
  on public.gallery_images for delete
  to anon
  using (true);

